import { ExternalLink, Printer } from "lucide-react";
import { useQr } from "../../../api/business";
import { Button, Card, ErrorState, Skeleton } from "../../../ui";
import { useBiz } from "../context";
import { BranchPicker, PageHeader } from "../shared";

export default function QrScreen() {
  const { business, branchId } = useBiz();
  const qr = useQr(branchId);
  const branch = business.branches.find((b) => b.id === branchId);
  return (
    <>
      <div className="no-print"><PageHeader title="QR codes" subtitle="Print one per table. Diners see your menu with nutrition, no app needed." actions={<BranchPicker />} /></div>
      {qr.isPending ? <Skeleton className="h-96" /> : qr.isError ? <ErrorState error={qr.error} onRetry={() => qr.refetch()} /> : (
        <Card className="mx-auto max-w-md space-y-4 text-center">
          <p className="font-display text-xl font-extrabold">{branch?.name}</p>
          {/* The SVG is generated by our own backend from the branch URL. */}
          <div className="mx-auto w-64 max-w-full rounded-2xl bg-white p-2 [&>svg]:h-auto [&>svg]:w-full" dangerouslySetInnerHTML={{ __html: qr.data.svg }} />
          <p className="text-sm text-muted">Scan to see what's in each dish</p>
          <p className="break-all text-xs text-muted">{qr.data.url}</p>
          <div className="no-print flex justify-center gap-2">
            <Button onClick={() => window.print()}><Printer size={18} /> Print</Button>
            <a href={`/q/${qr.data.branch_code}`} target="_blank" rel="noreferrer"><Button variant="secondary"><ExternalLink size={18} /> Open page</Button></a>
          </div>
        </Card>
      )}
    </>
  );
}
